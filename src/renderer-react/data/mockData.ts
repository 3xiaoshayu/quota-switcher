function remainingAsPercent(
  remaining: number | null,
  total: number,
  present?: boolean,
): number | null {
  if (present === false) return null;
  if (remaining == null || !Number.isFinite(remaining)) return null;
  if (!total || total === 100) return Math.round(remaining);
  return Math.max(0, Math.min(100, Math.round((remaining / total) * 100)));
}

export const previewAccountsForLens = (product: ProductKind = 'codex'): AccountQuota[] => {
  const now = Date.now();
  const source = product === 'antigravity'
    ? INITIAL_ANTIGRAVITY_ACCOUNTS
    : product === 'cursor'
      ? INITIAL_CURSOR_ACCOUNTS
      : INITIAL_ACCOUNTS;
  return source.map((account) => ({
    ...account,
    fiveHourQuotaRemaining: remainingAsPercent(
      account.fiveHourQuotaRemaining,
      account.fiveHourQuotaTotal,
      account.fiveHourQuotaPresent,
    ),
    fiveHourQuotaTotal: 100,
    weeklyQuotaRemaining: remainingAsPercent(
      account.weeklyQuotaRemaining,
      account.weeklyQuotaTotal,
      account.weeklyQuotaPresent,
    ),
    weeklyQuotaTotal: 100,
    fiveHourResetAt: product === 'codex' && account.fiveHourQuotaPresent !== false
      ? now + (3 * 60 * 60 * 1000)
      : null,
    weeklyResetAt: product === 'codex' && account.weeklyQuotaPresent !== false
      ? now + (4 * 24 * 60 * 60 * 1000)
      : null,
  }));
};
